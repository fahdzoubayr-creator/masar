# -*- coding: utf-8 -*-
"""يضيف ملف تعليمات _اقرأني.txt داخل كل مجلد محور رئيسي."""
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
INBOX = Path(__file__).resolve().parent.parent / "assets" / "banks" / "manual_inbox"

TEXT = """مجلد المحور الرئيسي: {folder}
================================

ما عليك إلا أن تفتح أي ملف هنا باسم المحور الفرعي، وتكتب أسئلتك تحته.
المسار ك��hence يحدّد المحور: اسم هذا المجلد = المحور الرئيسي، واسم الملف
= المحور الفرعي. لا حاجة لكتابة أي ترويسة.

صيغة السؤال (انسخها وكرّرها، وافصل بين الأسئلة بسطر من الشرطات ثم سطر فارغ):

الوضعية: وصف واقعي من الحصة يمهّد للسؤال.
السؤال: سؤال واحد واضح.
أ) الخيار الأول.
ب) الخيار الثاني.
ج) الخيار الثالث.
د) الخيار الرابع.
الإجابة: ب
الشرح: سطران: لماذا هي صحيحة، وأي خطأ شائع يقع فيه التلاميذ.

شروط إلزامية (يرفضها الفحص آلياً):
  - أربعة خيارات، ولا تكتب: كل الأجوبة السابقة خاطئة.
  - الإجابة الصحيحة ليست أطول الخيارات وحدها.
  - لا تعِد عبارة السؤال داخل الإجابة الصحيحة.
  - لا تكتب: هذا النص، ولا المقتطف.
  - الشرح مطلوب وليس اختيارياً.
  - لا حروف لاتينية داخل النص العربي.

بعد الكتابة شغّل:
    python tools/import_manual.py

الأمر يقرأ كل الملفات، ويوقف البناء إن وجد خطأ، ثم يبني بنك كل محور على
حدة ويحدّث التطبيق. تابع التقدّم بـ:
    python tools/check_manual.py

الهدف: أكثر من 100 سؤال لكل محور فرعي.
"""


def main():
    n = 0
    for d in sorted(INBOX.iterdir()):
        if not d.is_dir():
            continue
        f = d / "_اقرأني.txt"
        f.write_text(TEXT.format(folder=d.name), encoding="utf-8")
        topics = [x.stem for x in d.glob("*.txt") if not x.name.startswith("_")]
        n += 1
        print(f"{d.name}: {len(topics)} ملف محور فرعي")
    print(f"{n} مجلد رئيسي مع ملف تعليمات")


if __name__ == "__main__":
    main()