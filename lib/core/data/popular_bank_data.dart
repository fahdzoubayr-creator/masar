  ]);

  /// يدمج عدة بنوك في خريطة واحدة مع إلحاق أسئلة البنوك المتأخرة
  /// بقوائم البنوك السابقة عند تشابه المفاتيح.
  static Map<String, List<Question>> _merge(
      List<Map<String, List<Question>>> banks) {
    final out = <String, List<Question>>{};
    for (final bank in banks) {
      for (final entry in bank.entries) {
        out.update(entry.key, (existing) => [...existing, ...entry.value],
            ifAbsent: () => entry.value);
      }
    }
    return out;
  }
